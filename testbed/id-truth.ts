// Truth for S5 ID trace. Which fields hold the same identifier is stated by hand from how testbed/generate.ts and
// testbed/excel/generate.ts build the rows (the workbook's Visit ID is the encounter id under another name). Distinct and
// shared value counts are measured directly in each testbed, independently of the product. Raw values stay in this
// process: only counts are written.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { config } from 'dotenv';
import { Client } from 'pg';
import { runSqlServerAdminQuery } from './sqlserver/admin-query.js';
import { collectExcelColumns } from './excel/truth.js';

type Source = 'postgres' | 'sql_server' | 'excel';
const entities: Record<string, Array<[Source, string]>> = {
  patient: [['postgres', 'public.patients.patient_id'], ['postgres', 'public.encounters.patient_id'], ['sql_server', 'dbo.patients.patient_id'], ['sql_server', 'dbo.encounters.patient_id'],
    ['excel', 'Patients.patient_id'], ['excel', 'Visits.patient_id'], ['excel', 'Charges.patient_id'], ['excel', 'Registrations.patient_id']],
  encounter: [['postgres', 'public.encounters.encounter_id'], ['postgres', 'public.orders.encounter_id'], ['sql_server', 'dbo.encounters.encounter_id'], ['sql_server', 'dbo.orders.encounter_id'],
    ['excel', 'Visits.visit_id'], ['excel', 'Charges.visit_id']],
  mrn: [['postgres', 'public.patients.mrn'], ['sql_server', 'dbo.patients.mrn'], ['excel', 'Patients.mrn'], ['excel', 'Registrations.mrn']],
};

config({ path: resolve('.env') });
const pg = new Client({ connectionString: process.env.DATABASE_URL_TESTBED });
await pg.connect();
const excel = await collectExcelColumns();
const values = new Map<string, Set<string>>();
try {
  for (const fields of Object.values(entities)) for (const [source, field] of fields) {
    const split = field.lastIndexOf('.'); const table = field.slice(0, split); const column = field.slice(split + 1);
    let set: Set<string>;
    if (source === 'postgres') set = new Set((await pg.query<{ v: string }>(`SELECT DISTINCT "${column}"::text AS v FROM ${table.split('.').map((part) => `"${part}"`).join('.')} WHERE "${column}" IS NOT NULL`)).rows.map((row) => row.v));
    else if (source === 'sql_server') set = new Set(runSqlServerAdminQuery(`SET NOCOUNT ON; SELECT DISTINCT CAST([${column}] AS nvarchar(400)) FROM si_testbed_sqlserver.${table} WHERE [${column}] IS NOT NULL;`, 'si_testbed_sqlserver').split('\n').filter(Boolean));
    else set = new Set((excel[field] ?? (() => { throw new Error(`workbook column ${field} not found`); })()).filter((value) => value !== null).map(String));
    values.set(`${source}:${field}`, set);
  }
} finally { await pg.end(); }

const shared = (left: Set<string>, right: Set<string>) => [...left].filter((value) => right.has(value)).length;
const truth = Object.fromEntries(Object.entries(entities).map(([entity, fields]) => [entity, {
  fields: fields.map(([source, field]) => ({ source, field, distinct: values.get(`${source}:${field}`)!.size })),
  pairs: fields.flatMap(([leftSource, left], index) => fields.slice(index + 1).map(([rightSource, right]) => ({
    left: `${leftSource}:${left}`, right: `${rightSource}:${right}`, shared: shared(values.get(`${leftSource}:${left}`)!, values.get(`${rightSource}:${right}`)!) }))),
}]));
writeFileSync(resolve('testbed/id-truth.json'), `${JSON.stringify({ _note: 'Generated by pnpm testbed:id-truth. Entities stated by hand from the testbed generators; counts measured in each testbed.', ...truth }, null, 2)}\n`);
process.stdout.write('Wrote testbed/id-truth.json\n');
